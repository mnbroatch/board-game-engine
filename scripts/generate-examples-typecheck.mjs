import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const repoRoot = join(__dirname, "..");
const examplesDir = join(repoRoot, "examples");
const outFile = join(repoRoot, "tests", ".generated", "examples-typecheck.ts");

function toIdentifier(basename) {
  return basename
    .replace(/\.json$/i, "")
    .replace(/[^a-zA-Z0-9_$]+(.)/g, (_, chr) => chr.toUpperCase())
    .replace(/^[^a-zA-Z_$]/, "_$&");
}

const entries = (await readdir(examplesDir, { withFileTypes: true }))
  .filter((e) => e.isFile() && e.name.toLowerCase().endsWith(".json"))
  .map((e) => e.name)
  .sort();

const parsed = [];
for (const filename of entries) {
  const fullPath = join(examplesDir, filename);
  const raw = await readFile(fullPath, "utf8");
  parsed.push({ filename, json: JSON.parse(raw) });
}

await mkdir(dirname(outFile), { recursive: true });

const lines = [];
lines.push('import type { AuthoredGameRules } from "../../src/types/expanded-game-types.js";');
lines.push("");
lines.push("// This file is auto-generated by scripts/generate-examples-typecheck.mjs");
lines.push("// Do not edit by hand.");
lines.push("");
lines.push("export const examples = {");

for (const { filename, json } of parsed) {
  const id = toIdentifier(filename);
  const jsonText = JSON.stringify(json, null, 2);
  // Embed the JSON as a TS object literal so string literals stay narrow enough
  // for `satisfies BagelGame` checks (unlike `resolveJsonModule` imports).
  lines.push(`  ${id}: (${jsonText}) as const satisfies AuthoredGameRules,`);
}

lines.push("} as const;");
lines.push("");

await writeFile(outFile, lines.join("\n"), "utf8");

